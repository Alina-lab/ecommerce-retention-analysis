-- Этап 6. Проверка периода наблюдения перед расчётом возвратов.
-- Диалект: SQLite. Нужна orders.
-- Месяц определяется датой оформления, а delivered — итоговым статусом.
-- Таблица не показывает, в каком месяце заказ был фактически доставлен.

-- Вопрос: как распределены все и доставленные заказы по месяцам покупки?
-- Полный результат подтверждён в DBeaver.
-- Суммы строк: total_orders = 99441, delivered_orders = 96478.
-- Первые месяцы редкие: 2016-09 = 4/1, 2016-10 = 324/265, 2016-12 = 1/1
-- (в каждой паре все заказы / заказы с итоговым статусом delivered).
-- Последние месяцы: 2018-07 = 6292/6159, 2018-08 = 6512/6351,
-- 2018-09 = 16/0, 2018-10 = 4/0.
-- Поздние единичные заказы не подтверждают полноценное наблюдение
-- за повторными доставленными покупками до октября.
-- Причину такого распределения по этой таблице определить нельзя.
-- Следующий запрос уточняет последние дни покупок перед выбором границы.
SELECT
    SUBSTR(order_purchase_timestamp, 1, 7) AS purchase_month,
    COUNT(*) AS total_orders,
    SUM(
        CASE
            WHEN order_status = 'delivered' THEN 1
            ELSE 0
        END
    ) AS delivered_orders
FROM orders
GROUP BY purchase_month
ORDER BY purchase_month;

-- Вопрос: как выглядят последние дни оформления заказов?
-- Полный результат подтверждён в DBeaver.
-- 2018-08-20: 256 заказов, из них 251 с итоговым статусом delivered.
-- 2018-08-28: 44/39; 2018-08-29: 14/11.
-- 2018-08-30: 4/0; 2018-08-31: 1/0.
-- Все показанные более поздние даты также имеют 0 delivered.
-- Последняя показанная дата оформления — 2018-10-17.
-- В конце августа число покупок снижается; конец месяца нельзя
-- автоматически считать полным периодом наблюдения.
-- Это наблюдение не устанавливает причину снижения и не доказывает
-- прекращение покупок за пределами выгрузки.
SELECT
    SUBSTR(order_purchase_timestamp, 1, 10) AS purchase_day,
    COUNT(*) AS total_orders,
    SUM(
        CASE
            WHEN order_status = 'delivered' THEN 1
            ELSE 0
        END
    ) AS delivered_orders
FROM orders
WHERE order_purchase_timestamp >= '2018-08-20'
GROUP BY purchase_day
ORDER BY purchase_day;
