-- Этап 14. Сравнение двух выбранных категорий внутри месячных когорт.
-- Диалект: SQLite. Нужны представления из этапов 11 и 12.
-- Выбор Алины: fashion_bags_accessories и cool_stuff.
-- В общем результате этапа 13: 1039/50/4.81% и 2382/31/1.30% соответственно.
-- cool_stuff имеет низкую долю среди крупных показанных групп,
-- но не является абсолютным минимумом среди всех категорий.
-- Эти группы выбраны после просмотра результатов: анализ исследовательский.
-- Берём когорты января 2017 — января 2018 включительно.
-- Исключаем редкие ранние когорты и неполную когорту февраля 2018.
-- Это фильтр для сравнения, а не изменение определения метрики в базовом VIEW.
-- Месяц относится к первой покупке; у каждого покупателя своё окно 180 дней.
-- Повторная покупка может быть из любой категории.
-- Внутри месяца смотрим одновременно на размер группы, число повторов и процент.
-- Малые числа повторов дают нестабильные проценты.
-- Проверка по месяцам не устраняет все различия между группами и не доказывает причинность.
-- В месяце без покупателей категории строки не будет: это не нулевой возврат.
-- Запрос проверен на искусственных примерах.
-- Результат подтверждён в DBeaver 2026-10-07: 26 строк, 13 месяцев.
-- cool_stuff: 2366 покупателей, 30 повторных, 1.27%.
-- fashion_bags_accessories: 1028 покупателей, 49 повторных, 4.77%.
-- Эти суммы относятся к выбранным месячным когортам, а не ко всем покупателям этапа 13.
-- Доля у сумок выше в 11 из 13 месяцев; исключения — 2017-04 и 2017-07.
-- Размер группы сумок по месяцу: от 27 до 160 покупателей; повторов от 0 до 12.
-- Устойчивое направление описательного различия не доказывает причинность/значимость.
-- Месяц | cool_stuff: покупателей/повторов/% | сумки: покупателей/повторов/%
-- 2017-01 | 30/0/0.00 | 27/3/11.11
-- 2017-02 | 68/1/1.47 | 29/1/3.45
-- 2017-03 | 114/0/0.00 | 60/1/1.67
-- 2017-04 | 108/2/1.85 | 39/0/0.00
-- 2017-05 | 224/1/0.45 | 83/6/7.23
-- 2017-06 | 192/4/2.08 | 71/4/5.63
-- 2017-07 | 215/3/1.40 | 75/1/1.33
-- 2017-08 | 223/5/2.24 | 81/3/3.70
-- 2017-09 | 188/3/1.60 | 91/4/4.40
-- 2017-10 | 233/3/1.29 | 87/3/3.45
-- 2017-11 | 276/3/1.09 | 160/12/7.50
-- 2017-12 | 220/1/0.45 | 116/5/4.31
-- 2018-01 | 275/4/1.45 | 109/6/5.50
SELECT
    r.first_purchase_month,
    c.first_category,
    COUNT(*) AS buyers,
    SUM(r.returned_180) AS returned_buyers,
    ROUND(100.0 * AVG(r.returned_180), 2) AS repeat_purchase_rate_180
FROM buyer_retention_180 AS r
JOIN buyer_first_category AS c
    ON r.customer_unique_id = c.customer_unique_id
WHERE c.first_category IN (
    'fashion_bags_accessories',
    'cool_stuff'
)
    AND r.first_purchase_month BETWEEN '2017-01' AND '2018-01'
GROUP BY r.first_purchase_month, c.first_category
ORDER BY r.first_purchase_month, c.first_category;
